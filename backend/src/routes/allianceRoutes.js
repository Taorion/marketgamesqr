const express=require('express');
const {z}=require('zod');
const {authRequired,requireRoles}=require('../middleware/auth');
const {requirePortalAccess,requireBusinessFeature}=require('../middleware/subscription');
const {invalidateBusinessResponseCache}=require('../middleware/businessResponseCache');
const {rateLimit}=require('../middleware/rateLimit');
const {forbidden}=require('../utils/http');
const S=require('../services/allianceService');
const {parse,uuid}=require('../services/allianceRules');
const router=express.Router(),publicRouter=express.Router();
const handle=f=>async(req,res,next)=>{try{res.set('Cache-Control','private, no-store');res.json(await f(req));}catch(e){next(e);}};
const id=req=>parse(uuid,req.params.id);
const publicToken=v=>parse(z.string().regex(/^[a-f0-9]{64}$/),v);
router.use(authRequired,requirePortalAccess,requireRoles('BUSINESS_OWNER','BUSINESS_MANAGER','ADMIN','ADMIN_MARKET_GAMES'));
router.use((req,_res,next)=>req.user.business_id?next():next(forbidden('Selecciona una cuenta de negocio.')));
router.use(invalidateBusinessResponseCache());
router.get('/context',handle(req=>S.context(req.user)));
router.get('/partner',handle(req=>S.lookup(req.user,parse(z.string().min(2).max(120),req.query.slug))));
router.post('/',requireBusinessFeature('qr_batch_generator'),handle(req=>S.save(req.user,req.body)));
router.get('/:id',handle(req=>S.detail(req.user,id(req),parse(z.coerce.number().int().min(0).max(1000000).default(0),req.query.offset))));
router.put('/:id',handle(req=>S.save(req.user,req.body,id(req))));
router.delete('/:id',handle(req=>S.remove(req.user,id(req))));
router.post('/:id/actions',handle(req=>S.action(req.user,id(req),req.body)));
router.put('/:id/branding',handle(req=>S.personalize(req.user,id(req),req.body)));
router.post('/:id/batches',requireBusinessFeature('qr_batch_generator'),handle(req=>S.issue(req.user,id(req),req.body)));
router.post('/:id/batches/:batch/close',handle(req=>S.returnBatch(req.user,id(req),parse(uuid,req.params.batch),req.body.reason)));
router.post('/:id/payments',handle(req=>S.pay(req.user,id(req),req.body)));
router.post('/:id/payments/:payment/reverse',handle(req=>S.reversePayment(req.user,id(req),parse(uuid,req.params.payment),req.body.reason)));
router.post('/:id/tickets/:ticket/cancel',handle(req=>S.cancelTicket(req.user,id(req),parse(uuid,req.params.ticket),req.body.reason)));
publicRouter.use(rateLimit({keyPrefix:'alliance-public',max:100,windowMs:15*60000}));
publicRouter.get('/tickets/:token',handle(req=>S.publicTicket(publicToken(req.params.token))));
publicRouter.get('/:token',handle(req=>S.publicAgreement(publicToken(req.params.token))));
publicRouter.post('/:token/enroll',rateLimit({keyPrefix:'alliance-enroll',max:15,windowMs:15*60000}),handle(req=>S.enroll(publicToken(req.params.token),req.body)));
module.exports={router,publicRouter};
